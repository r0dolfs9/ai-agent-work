"""Additional-country selection rubric (deliverable C/D support).

Run:  python3 agri-rules/models/country_score.py
Writes agri-rules/models/country_score_results.md

Every score is an INTERPRETATION (1 = worst, 5 = best for this project) except
criterion 1, which is mechanically derived from Eurostat aact_eaa01 (2024 output
of the agricultural industry, basic prices, EUR million; retrieved 2026-10-14,
dataset updated 2026-05-13). Weights are ASSUMPTIONS; change them and rerun.
Evidence for each score is in 03-source-matrix.md and 12-evidence-ledger.md.
"""
import sys
from pathlib import Path

# (criterion, weight). Weights sum to 100.
CRITERIA = [
    ("Agricultural importance (Eurostat 2024 output)", 15),
    ("Regulatory distinctiveness", 10),
    ("Client or research value [audience undecided]", 10),
    ("Availability/reliability of official sources", 15),
    ("Language coverage (models + reviewer access)", 5),
    ("Consolidated legislation available", 10),
    ("Technical access (probe 2026-10-14; 5 = easy)", 10),
    ("Maintenance cost (5 = cheap; regions/agreements raise cost)", 10),
    ("Added insight vs the 8 selected countries", 15),
]

# Eurostat aact_eaa01, AM180000, PRD_BP, MIO_EUR, 2024 (VERIFIED FACT, see ledger E-C01)
OUTPUT_2024_MEUR = {
    "Italy": 70213.96, "Romania": 20211.93, "Denmark": 12613.07, "Ireland": 12456.8,
    "Austria": 9932.14, "Finland": 5506.64, "Lithuania": 4432.29,
}


def output_score(meur: float) -> int:
    """CALCULATION: bands chosen before scoring (ASSUMPTION)."""
    if meur >= 40000:
        return 5
    if meur >= 20000:
        return 4
    if meur >= 10000:
        return 3
    if meur >= 4000:
        return 2
    return 1


# Scores for criteria 2..9 (INTERPRETATION; one-line reasons in 03-source-matrix.md §D.3)
SCORES = {
    #            dist client src lang cons access maint insight
    "Italy":     [5,   4,     4,  4,   4,   3,     2,    4],
    "Denmark":   [4,   3,     5,  3,   5,   5,     4,    3],
    "Ireland":   [4,   3,     3,  5,   2,   4,     4,    4],
    "Austria":   [3,   3,     5,  5,   5,   5,     3,    2],
    "Finland":   [3,   3,     5,  3,   5,   5,     4,    2],
    "Romania":   [3,   3,     2,  3,   2,   1,     3,    4],
    "Lithuania": [2,   3,     3,  3,   4,   1,     4,    2],
}


def total(country: str, weights=None) -> float:
    w = weights or [c[1] for c in CRITERIA]
    s = [output_score(OUTPUT_2024_MEUR[country])] + SCORES[country]
    return 100 * sum(wi * si for wi, si in zip(w, s)) / (5 * sum(w))  # normalised, max 100


def main() -> None:
    names = sorted(SCORES, key=total, reverse=True)
    lines = ["# Additional-country scoring (generated by country_score.py)", "",
             "Score = 100 × Σ(weight × score 1–5) / (5 × Σweights), so the maximum is 100. "
             "Criterion 1 is computed from Eurostat output; the rest are INTERPRETATION.", "",
             "| Country | Output 2024 €m | " + " | ".join(f"C{i+1} (w{c[1]})" for i, c in enumerate(CRITERIA)) + " | **Total** |",
             "|---|---|" + "---|" * len(CRITERIA) + "---|"]
    for n in names:
        s = [output_score(OUTPUT_2024_MEUR[n])] + SCORES[n]
        lines.append(f"| {n} | {OUTPUT_2024_MEUR[n]:,.0f} | " + " | ".join(map(str, s)) + f" | **{total(n):.1f}** |")
    lines += ["", "Criteria: " + "; ".join(f"C{i+1} = {c[0]}" for i, c in enumerate(CRITERIA)), ""]

    # Sensitivity: the three alternative weightings named in 03-source-matrix.md
    base = [c[1] for c in CRITERIA]
    scen = {
        "Base weights": base,
        "Cheap internal pilot (access ×2, maintenance ×2, client value 0)": [15, 10, 0, 15, 5, 10, 20, 20, 15],
        "Client product (client value ×2, importance ×1.5)": [22, 10, 20, 15, 5, 10, 10, 10, 15],
        "Equal weights": [11.11] * 9,
    }
    lines += ["## Sensitivity (CALCULATION)", "", "| Weighting | Ranking (score) |", "|---|---|"]
    for label, w in scen.items():
        rank = sorted(SCORES, key=lambda n: total(n, w), reverse=True)
        lines.append(f"| {label} | " + " > ".join(f"{n} {total(n, w):.1f}" for n in rank[:4]) + " |")
    out = Path(__file__).with_name("country_score_results.md")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
