#!/usr/bin/env python3
"""Build pilot-scope-agriculture.md from the verified EUR-Lex query result (data/results/05_pilot_candidates.csv).

The grouping into sub-domains and the proof-of-concept (PoC) selection are our ASSUMPTIONS; titles, in-force status
and Latvian NIM counts come from the query [S142][S143].
Run: python3 feasibility/eu-lv-regulatory-comparison/build_scope.py
"""
import csv, pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROWS = {r["celex"]: r for r in csv.DictReader(open(HERE / "data/results/05_pilot_candidates.csv", encoding="utf-8"))}
RETRIEVED = (HERE / "data/results/RETRIEVED.txt").read_text().strip()

GROUPS = [
    ("CAP support and conditionality", ["32021R2115", "32021R2116", "32021R2117", "32013R1308", "32022R1172", "32022R1173"]),
    ("Nutrients, water and air", ["31991L0676", "32016L2284", "32000L0060", "32019R1009", "32020R0741"]),
    ("Industrial emissions (large pig and poultry farms)", ["32010L0075", "32024L1785"]),
    ("Nature and land use", ["31992L0043", "32009L0147", "32024R1991"]),
    ("Plant protection and residues", ["32009R1107", "32009L0128", "32005R0396", "32016R2031"]),
    ("Seeds, varieties and GMOs", ["31966L0401", "31966L0402", "32002L0053", "32002L0055", "32002L0057", "32001L0018", "32015L0412"]),
    ("Animal health, identification and veterinary medicines", ["32016R0429", "32000R1760", "32019R0006", "32019R0004"]),
    ("Farm-animal welfare, transport and slaughter", ["31998L0058", "32008L0119", "32008L0120", "31999L0074", "32007L0043", "32005R0001", "32009R1099"]),
    ("Feed, food hygiene, by-products and official controls", ["32005R0183", "32009R1069", "32017R0625", "32002R0178", "32004R0852", "32004R0853"]),
    ("Organic production", ["32018R0848"]),
    ("Supply chain, trade and state aid", ["32019L0633", "32023R1115", "32022R2472", "32013R1408"]),
    ("Farm employment: working time, working conditions, safety, seasonal workers", ["32003L0088", "32019L1152", "31989L0391", "32009L0104", "32014L0036"]),
]
POC = {"31991L0676", "32016L2284", "32019R1009",                      # nutrients
       "32009R1107", "32009L0128",                                    # plant protection
       "31998L0058", "32008L0119", "32008L0120", "31999L0074", "32007L0043"}  # farm-animal welfare

listed = [c for _, cs in GROUPS for c in cs]
assert len(listed) == len(set(listed)) == len(ROWS), (len(listed), len(set(listed)), len(ROWS))
assert set(listed) == set(ROWS)

L = ["# Pilot scope: core EU acts for agriculture\n",
     f"Generated by `build_scope.py` from `data/results/05_pilot_candidates.csv` ({RETRIEVED} from the EU Publications Office "
     "SPARQL endpoint [S142][S143]). **All 49 acts were confirmed in force.** The grouping and the proof-of-concept (PoC) "
     "choice are our ASSUMPTIONS for discussion, not a final scope.\n",
     "*LV records* = national implementing measures that Latvia has notified for the act and that EUR-Lex holds. "
     "Regulations apply directly, so they normally have none. For them, the Latvian side (national options, penalties, "
     "competent authorities) has to be found by search; no ready-made mapping exists.\n"]
n_poc = 0
for name, cs in GROUPS:
    L.append(f"\n## {name}\n")
    L.append("| CELEX | Act | LV records | PoC |\n|---|---|---:|:---:|")
    for c in cs:
        r = ROWS[c]
        assert r["inforce"] == "1", c
        title = r["title"].replace("|", "/").strip()
        if len(title) > 160:
            title = title[:157].rstrip() + "…"
        poc = "✓" if c in POC else ""
        n_poc += c in POC
        L.append(f"| [{c}](https://eur-lex.europa.eu/legal-content/LV/TXT/?uri=CELEX:{c}) | {title} | {r['lv_nim']} | {poc} |")
regs = [c for c in ROWS if c[5] == "R"]
dirs = [c for c in ROWS if c[5] == "L"]
L.append("\n## Summary\n")
L.append("- The employment group was added after the owner's overtime-pay example. EU law sets the 48-hour average limit "
         "including overtime (Directive 2003/88, Art. 6) and requires employers to tell workers in writing how overtime is "
         "paid (Directive 2019/1152, Art. 4(2)(l)). It does **not** set an overtime pay rate; that rate is purely national. "
         "Directives 2019/1152, 89/391 and 2009/104 are also part of CAP social conditionality (Regulation 2021/2115, Annex IV) [S166][S167][S168].")
L.append(f"- {len(ROWS)} acts: {len(dirs)} directives and {len(regs)} regulations. Proof of concept: {n_poc} acts in 3 sub-domains.")
L.append(f"- Latvian implementing-measure records: {sum(int(ROWS[c]['lv_nim']) for c in dirs)} across the directives, "
         f"{sum(int(ROWS[c]['lv_nim']) for c in regs)} across the regulations.")
L.append("- Directive (EU) 2024/1785 (revised Industrial Emissions Directive) had a transposition date of 1 July 2026 "
         "(`data/results/06_transposition_deadlines.csv`). EUR-Lex held no Latvian measure for it on 13 October 2026. "
         "That may be late transposition or a lag in the database. The pilot would check it, not assume either.")
(HERE / "pilot-scope-agriculture.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote pilot-scope-agriculture.md;", len(ROWS), "acts;", n_poc, "PoC")
