#!/usr/bin/env python3
"""AI-usage cost of the owner's multi-agent, multi-country plan, for four model mixes (2026-10-13).

Plan being costed (owner's description, 13 Oct 2026): EU rules first, then the same rules in Latvia + 8 other countries
(10 jurisdictions), about 100 rules/topics for agriculture. Per rule and jurisdiction a READER agent finds, reads,
translates and files the rule; a SUPERVISOR agent checks each filed rule. Per topic a COMPARER writes the differences and
real-world effects, a VERIFIER checks them, and a FINAL CHECKER checks the one-page result (links are checked by code).

Prices: [S044] Claude, [S045] OpenAI, [S046] Google, [S173] DeepSeek (peak hours; off-peak is half), [S174] Qwen
(Singapore, requests <=256K tokens), [S181] Mistral. Token counts, search counts and re-runs are ASSUMPTIONS.
Run: python3 feasibility/eu-lv-regulatory-comparison/stack_costs.py -> stack_costs_results.md
"""
import pathlib

OUT = pathlib.Path(__file__).resolve().parent
USD_PER_EUR = 1.1206          # ECB 2026-10-09
SEARCH_USD = 10 / 1000        # web search, $10 per 1,000 [S044][S045]; assumed similar for a stand-alone search API
OPENROUTER_FEE = 0.055        # 5.5% on credit purchases [S176]; set to 0 when paying providers directly
TOPICS, JURIS = 100, 10       # ASSUMPTION: 100 agriculture rules x (EU + Latvia + 8 countries)

PRICE = {  # USD per 1M tokens: (input, output)
    "Claude Opus 5.5": (4.00, 20.00), "Claude Sonnet 5.5": (2.00, 10.00), "Claude Haiku 5.5": (0.10, 0.50),
    "GPT-5.5": (5.00, 30.00), "GPT-5.4-mini": (0.75, 4.50), "Gemini 3.1 Pro": (2.00, 12.00),
    "DeepSeek V4 Pro": (1.32, 3.96), "DeepSeek Flash": (0.30, 1.20),
    "Qwen3.8 Max": (2.00, 6.00), "Qwen3.7 Plus": (0.40, 1.60), "Qwen3.8 Flash": (0.15, 0.47),
    "Mistral Large": (0.50, 1.50),
}
# ASSUMPTION: tokens per unit of work (input, output); readers browse and read long legal texts, so they dominate
TOKENS = {
    "low":  dict(reader=(60_000, 6_000),   supervisor=(20_000, 1_000), comparer=(40_000, 6_000),
                 verifier=(40_000, 3_000), final=(20_000, 2_000), searches=3, reruns=1.5),
    "base": dict(reader=(150_000, 10_000), supervisor=(40_000, 2_000), comparer=(80_000, 10_000),
                 verifier=(80_000, 6_000), final=(30_000, 3_000), searches=6, reruns=2.5),
    "high": dict(reader=(400_000, 20_000), supervisor=(80_000, 4_000), comparer=(150_000, 20_000),
                 verifier=(150_000, 10_000), final=(50_000, 5_000), searches=12, reruns=4.0),
}
MIXES = {
    "A. All Claude": dict(reader="Claude Sonnet 5.5", supervisor="Claude Haiku 5.5", comparer="Claude Opus 5.5",
                          verifier="Claude Opus 5.5", final="Claude Haiku 5.5"),
    "B. Mixed (suggested)": dict(reader="Qwen3.7 Plus", supervisor="DeepSeek Flash", comparer="Claude Opus 5.5",
                                 verifier="GPT-5.5", final="Claude Sonnet 5.5"),
    "C. Chinese models only": dict(reader="DeepSeek V4 Pro", supervisor="DeepSeek Flash", comparer="Qwen3.8 Max",
                                       verifier="DeepSeek V4 Pro", final="Qwen3.8 Flash"),
    "D. Premium": dict(reader="Claude Opus 5.5", supervisor="Claude Sonnet 5.5", comparer="Claude Opus 5.5",
                       verifier="GPT-5.5", final="Claude Opus 5.5"),
}
UNITS = {"reader": TOPICS * JURIS, "supervisor": TOPICS * JURIS, "comparer": TOPICS, "verifier": TOPICS, "final": TOPICS}


def cost(mix: dict, case: str, fee: float = OPENROUTER_FEE) -> dict:
    t = TOKENS[case]
    parts = {}
    for role, n in UNITS.items():
        tin, tout = t[role]
        p_in, p_out = PRICE[mix[role]]
        parts[role] = n * (tin * p_in + tout * p_out) / 1e6 * t["reruns"]
    parts["web searches"] = TOPICS * JURIS * t["searches"] * SEARCH_USD * t["reruns"]
    usd = sum(parts.values()) * (1 + fee)
    return dict(parts=parts, usd=usd, eur=usd / USD_PER_EUR)


def main() -> None:
    L = ["# AI-usage cost of the multi-agent, multi-country plan\n",
         f"Generated by `stack_costs.py` (2026-10-13). {TOPICS} rules × {JURIS} jurisdictions (EU + Latvia + 8 countries). "
         f"Includes re-runs and a {OPENROUTER_FEE:.1%} OpenRouter fee. EUR at 1.1206 USD/EUR. Token counts are ASSUMPTIONS; prices are dated sources.\n",
         "## Total AI usage for one full run (EUR)\n",
         "| Model mix | Reader | Supervisor | Comparer | Verifier | Final check | Low | **Base** | High |",
         "|---|---|---|---|---|---|---:|---:|---:|"]
    for name, mix in MIXES.items():
        c = {k: cost(mix, k)["eur"] for k in TOKENS}
        L.append(f"| {name} | {mix['reader']} | {mix['supervisor']} | {mix['comparer']} | {mix['verifier']} | {mix['final']} | "
                 f"{c['low']:,.0f} | **{c['base']:,.0f}** | {c['high']:,.0f} |")
    L.append("\n## Where the money goes (base case, USD before fee)\n")
    L.append("| Model mix | Readers | Supervisor | Comparer | Verifier | Final check | Web searches |")
    L.append("|---|---:|---:|---:|---:|---:|---:|")
    for name, mix in MIXES.items():
        p = cost(mix, "base")["parts"]
        L.append(f"| {name} | {p['reader']:,.0f} | {p['supervisor']:,.0f} | {p['comparer']:,.0f} | {p['verifier']:,.0f} | {p['final']:,.0f} | {p['web searches']:,.0f} |")
    L.append("\nReaders (1,000 rule-by-country jobs) are most of the cost, so they are where a cheaper model saves money. "
             "The comparer and verifier run only 100 times each, so the best models cost little there.\n")
    # ---- first three months, cash (ASSUMPTIONS unless a source is given)
    BUDGET = {  # low / base / high
        "AI usage: one full run, mix B, plus 50% for test runs": [cost(MIXES["B. Mixed (suggested)"], k)["eur"] * 1.5 for k in TOKENS],
        "Server, 3 months (CPX22 about EUR 20 or CPX32 about EUR 36/month + IPv4) [S178]": [3 * 20.5, 3 * 36.5, 3 * 36.5],
        "n8n: self-hosted free, or cloud Pro EUR 50/month [S177]": [0, 0, 150],
        "Optional lawyer spot-check of the final pages (0 / 5 h at EUR 90 / 10 h at EUR 150)": [0, 450, 1500],
    }
    L.append("## Cash budget for the first three months (EUR)\n")
    L.append("| Item | Low | Base | High |\n|---|---:|---:|---:|")
    tot = [0.0, 0.0, 0.0]
    for item, v in BUDGET.items():
        L.append(f"| {item} | {v[0]:,.0f} | {v[1]:,.0f} | {v[2]:,.0f} |")
        tot = [t + x for t, x in zip(tot, v)]
    L.append(f"| **Total** | **{tot[0]:,.0f}** | **{tot[1]:,.0f}** | **{tot[2]:,.0f}** |\n")
    L.append("Not included: your own time, and any AI subscription you already pay for and use to build the system.\n")
    (OUT / "stack_costs_results.md").write_text("\n".join(L) + "\n")
    print("3-month totals", [round(t) for t in tot])
    for name, mix in MIXES.items():
        print(name, {k: round(cost(mix, k)["eur"]) for k in TOKENS})


if __name__ == "__main__":
    main()
