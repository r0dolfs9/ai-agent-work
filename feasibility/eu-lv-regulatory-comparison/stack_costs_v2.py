#!/usr/bin/env python3
"""Costs of the v2 pipeline (agent-setup-v2.md): fixed steps in n8n, one AI model chosen per step (2026-10-13).

Steps per rule (R = 100 rules) and per rule x jurisdiction (C = R x 10):
  rule_mapper (R)  finder (C)  extractor (C)  checker_ai (C)  context (R)  comparer (R)  verifier (R)  page_qa (R)
Fetching official texts, link/quote checks, page layout and the PDF are code (no AI cost).

Prices: [S044] Claude, [S045] OpenAI, [S046] Google (incl. search grounding), [S173] DeepSeek (peak), [S174] Qwen,
[S181] Mistral, [S200] Brave Search API ($5 per 1,000). Token counts, searches and re-runs are ASSUMPTIONS.
Run: python3 feasibility/eu-lv-regulatory-comparison/stack_costs_v2.py -> stack_costs_v2_results.md
"""
import pathlib

OUT = pathlib.Path(__file__).resolve().parent
USD_PER_EUR = 1.1206          # ECB 2026-10-09
OPENROUTER_FEE = 0.055        # [S176]
SEARCH_USD = 5 / 1000         # Brave Search API [S200]
R, J = 100, 10
C = R * J

PRICE = {  # USD per 1M tokens (input, output)
    "Claude Opus 5.5": (4.00, 20.00), "Claude Sonnet 5.5": (2.00, 10.00), "Claude Haiku 5.5": (0.10, 0.50),
    "GPT-5.5": (5.00, 30.00), "GPT-5.4-mini": (0.75, 4.50),
    "Gemini 3.1 Pro": (2.00, 12.00), "Gemini 3 Flash": (0.50, 3.00),
    "DeepSeek Flash": (0.30, 1.20), "Qwen3.8 Max": (2.00, 6.00), "Qwen3.7 Plus": (0.40, 1.60),
    "Mistral Large": (0.50, 1.50),
}
STEPS = {  # step: (runs, (tokens_in, tokens_out) low/base/high)  ASSUMPTION
    "rule_mapper": (R, [(30_000, 4_000), (60_000, 8_000), (120_000, 15_000)]),
    "finder":      (C, [(40_000, 1_000), (100_000, 2_000), (250_000, 4_000)]),
    "extractor":   (C, [(15_000, 2_000), (30_000, 4_000), (60_000, 8_000)]),
    "checker_ai":  (C, [(5_000, 500), (10_000, 1_000), (20_000, 2_000)]),
    "context":     (R, [(30_000, 3_000), (60_000, 6_000), (150_000, 12_000)]),
    "comparer":    (R, [(30_000, 6_000), (60_000, 10_000), (120_000, 20_000)]),
    "verifier":    (R, [(30_000, 4_000), (60_000, 8_000), (120_000, 15_000)]),
    "page_qa":     (R, [(10_000, 2_000), (20_000, 3_000), (40_000, 5_000)]),
}
SEARCHES = {"finder_per_cell": [1, 3, 6], "context_per_rule": [5, 10, 20]}   # ASSUMPTION (fallback web searches)
RERUNS = [1.5, 2.5, 4.0]                                                     # ASSUMPTION
CASES = ["low", "base", "high"]

MIXES = {
    "Suggested": dict(rule_mapper="Claude Opus 5.5", finder="Gemini 3 Flash", extractor="Qwen3.7 Plus",
                      checker_ai="Claude Haiku 5.5", context="Claude Sonnet 5.5", comparer="Claude Opus 5.5",
                      verifier="GPT-5.5", page_qa="Claude Haiku 5.5"),
    "EU-leaning (Mistral readers)": dict(rule_mapper="Claude Opus 5.5", finder="Mistral Large", extractor="Mistral Large",
                      checker_ai="Claude Haiku 5.5", context="Claude Sonnet 5.5", comparer="Claude Opus 5.5",
                      verifier="Gemini 3.1 Pro", page_qa="Claude Haiku 5.5"),
    "Cheapest sensible": dict(rule_mapper="Gemini 3.1 Pro", finder="DeepSeek Flash", extractor="Qwen3.7 Plus",
                      checker_ai="Claude Haiku 5.5", context="Gemini 3 Flash", comparer="Qwen3.8 Max",
                      verifier="Gemini 3.1 Pro", page_qa="Claude Haiku 5.5"),
    "Premium": dict(rule_mapper="Claude Opus 5.5", finder="Claude Sonnet 5.5", extractor="Claude Sonnet 5.5",
                      checker_ai="Claude Sonnet 5.5", context="Claude Opus 5.5", comparer="Claude Opus 5.5",
                      verifier="GPT-5.5", page_qa="Claude Sonnet 5.5"),
}
# Optional translation specialist: DeepL API, about EUR 22-28 per 1M characters (third-party, conflicting) [S186]
DEEPL_EUR_PER_M_CHARS = 25.0
CHARS_PER_CELL = [5_000, 10_000, 20_000]                                     # ASSUMPTION


def run(mix: dict, i: int) -> dict:
    parts = {}
    for step, (n, toks) in STEPS.items():
        tin, tout = toks[i]
        p_in, p_out = PRICE[mix[step]]
        parts[step] = n * (tin * p_in + tout * p_out) / 1e6 * RERUNS[i]
    parts["web searches"] = (C * SEARCHES["finder_per_cell"][i] + R * SEARCHES["context_per_rule"][i]) * SEARCH_USD * RERUNS[i]
    usd = sum(parts.values()) * (1 + OPENROUTER_FEE)
    return dict(parts=parts, usd=usd, eur=usd / USD_PER_EUR)


def main() -> None:
    L = ["# Costs of the v2 pipeline (fixed steps, model per step)\n",
         f"Generated by `stack_costs_v2.py` (2026-10-13). {R} rules × {J} jurisdictions = {C:,} rule-by-country jobs. "
         f"Includes re-runs, a {OPENROUTER_FEE:.1%} OpenRouter fee and fallback web searches at $5 per 1,000. EUR at 1.1206 USD/EUR. "
         "Token counts are ASSUMPTIONS.\n",
         "## AI usage for one full run (EUR)\n",
         "| Mix | Rule list | Finder | Extractor | Check (AI part) | Real-world context | Comparer | Verifier | Page QA | Low | **Base** | High |",
         "|---|---|---|---|---|---|---|---|---|---:|---:|---:|"]
    for name, m in MIXES.items():
        e = [run(m, i)["eur"] for i in range(3)]
        L.append(f"| {name} | {m['rule_mapper']} | {m['finder']} | {m['extractor']} | {m['checker_ai']} | {m['context']} | "
                 f"{m['comparer']} | {m['verifier']} | {m['page_qa']} | {e[0]:,.0f} | **{e[1]:,.0f}** | {e[2]:,.0f} |")
    L.append("\n## Where the money goes, suggested mix, base case (USD before fee)\n")
    p = run(MIXES["Suggested"], 1)["parts"]
    LABEL = {"rule_mapper": "Rule list", "finder": "Finder", "extractor": "Extractor", "checker_ai": "Check (AI)",
             "context": "Real-world context", "comparer": "Comparer", "verifier": "Verifier", "page_qa": "Page QA",
             "web searches": "Web searches"}
    L.append("| " + " | ".join(LABEL[k] for k in p) + " |")
    L.append("|" + "---:|" * len(p))
    L.append("| " + " | ".join(f"{v:,.0f}" for v in p.values()) + " |")
    deepl = [C * CHARS_PER_CELL[i] / 1e6 * DEEPL_EUR_PER_M_CHARS for i in range(3)]
    L.append(f"\nOptional DeepL translation of every extracted rule (one pass): about €{deepl[0]:,.0f} / €{deepl[1]:,.0f} / €{deepl[2]:,.0f} (low / base / high).\n")

    sug = [run(MIXES["Suggested"], i)["eur"] for i in range(3)]
    budget = {
        "AI usage: one full run (suggested mix) + 50% for tests and the model bake-off": [x * 1.5 for x in sug],
        "Server, 3 months (4 vCPU / 8 GB, about EUR 36/month + IPv4) [S178]": [3 * 20.5, 3 * 36.5, 3 * 36.5],
        "Domain name for the server (HTTPS address)": [0, 15, 15],
        "Optional DeepL translation cross-check": [0, deepl[1], deepl[2]],
        "Optional lawyer spot-check (0 / 5 h at EUR 90 / 10 h at EUR 150)": [0, 450, 1500],
    }
    L.append("## Cash budget, first three months (EUR)\n")
    L.append("| Item | Low | Base | High |\n|---|---:|---:|---:|")
    tot = [0.0, 0.0, 0.0]
    for k, v in budget.items():
        L.append(f"| {k} | {v[0]:,.0f} | {v[1]:,.0f} | {v[2]:,.0f} |")
        tot = [a + b for a, b in zip(tot, v)]
    L.append(f"| **Total** | **{tot[0]:,.0f}** | **{tot[1]:,.0f}** | **{tot[2]:,.0f}** |\n")
    L.append("n8n itself is free when self-hosted [S177]. Not included: your own time and existing AI subscriptions.\n")
    (OUT / "stack_costs_v2_results.md").write_text("\n".join(L) + "\n")
    for name, m in MIXES.items():
        print(name, [round(run(m, i)["eur"]) for i in range(3)])
    print("budget", [round(t) for t in tot], "deepl", [round(d) for d in deepl])


if __name__ == "__main__":
    main()
