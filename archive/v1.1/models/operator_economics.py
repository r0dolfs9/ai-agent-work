#!/usr/bin/env python3
"""Operator economics for a Latvia-based business selling agent services/software globally.

Complements cost_model.py (which models the cost of running agents). This file models
what happens to revenue between the customer's payment and the owner's pocket:
payment fees, VAT treatment by customer type, merchant-of-record alternatives,
fixed company costs and profit distribution.

ALL tax statements are simplified illustrations of published rules, not tax advice.
Run: python3 models/operator_economics.py  ->  models/operator_economics_results.md
Currency: EUR. USD converted at the ECB reference rate 1.1206 USD per EUR (2026-10-09).
"""
from __future__ import annotations
import pathlib

OUT = pathlib.Path(__file__).resolve().parent
USD_PER_EUR = 1.1206                   # ECB reference rate 2026-10-09 (ECB Data API, EXR.D.USD.EUR.SP00.A)

# ---------------------------------------------------------------- dated inputs
STRIPE = {  # [S104] Stripe Latvia pricing, retrieved 2026-10-12
    "eea_standard": (0.015, 0.25), "eea_premium": (0.028, 0.25),
    "uk": (0.025, 0.25), "international": (0.0315, 0.25),
}
STRIPE_FX = 0.02                       # [S104] +2% if currency conversion is required
STRIPE_TAX_BASIC = 0.005               # [S104] 0.5% per transaction where registered (no-code)
STRIPE_MANAGED_PAYMENTS = 0.035        # [S104] MoR fee on top of processing (eligibility for LV unconfirmed)
PADDLE = (0.05, 0.50 / USD_PER_EUR)    # [S105] 5% + 50 US cents
VAT_LV = 0.21                          # [S100] Latvian standard rate
VAT_EU_TYPICAL = 0.21                  # ASSUMPTION: average EU B2C rate for illustration (actual 17-27%)
CIT_STANDARD = 0.20                    # [S100] on gross distributed profit
CIT_ALT, PIT_ALT = 0.15, 0.06          # [S100] alternative regime (individual-owned companies)
SIA_FEE = 75.0                         # [S102] one-off state fee
ACCOUNTANT_MONTH = (120, 200, 350)     # ASSUMPTION low/base/high outsourced bookkeeping incl. VAT/OSS returns
BANK_MONTH = (5, 15, 30)               # ASSUMPTION business account fees
OTHER_MONTH = (20, 60, 150)            # ASSUMPTION software, domain, insurance excl. professional indemnity


def stripe_net(price_gross: float, card: str, fx: bool) -> float:
    pct, fixed = STRIPE[card]
    fee = price_gross * (pct + (STRIPE_FX if fx else 0)) + fixed
    return price_gross - fee


def scenario_subscription(price_net: float = 49.0) -> list[dict]:
    """One monthly subscription sale of EUR 49 (net of VAT) to each customer type."""
    rows = []
    cases = [
        ("EU consumer (B2C), OSS: VAT of customer's country added", "B2C_EU", "eea_standard", False),
        ("EU business with VAT ID (B2B): reverse charge, no VAT charged", "B2B_EU", "eea_standard", False),
        ("Latvian customer (B2B or B2C): Latvian VAT 21%", "LV", "eea_standard", False),
        ("US business or consumer: outside EU VAT; local US sales-tax rules may apply (not modelled)", "US", "international", True),
        ("UK business: outside EU VAT (UK VAT reverse-charge by customer)", "UK", "uk", True),
    ]
    for label, kind, card, fx in cases:
        vat = price_net * (VAT_EU_TYPICAL if kind == "B2C_EU" else VAT_LV if kind == "LV" else 0)
        gross = price_net + vat
        s_net = stripe_net(gross, card, fx) - vat                    # seller remits VAT itself
        s_net_tax = s_net - gross * STRIPE_TAX_BASIC if vat else s_net
        p_net = gross - (gross * PADDLE[0] + PADDLE[1]) - 0          # MoR remits VAT; seller receives net of tax
        p_net -= vat
        mp_net = stripe_net(gross, card, fx) - gross * STRIPE_MANAGED_PAYMENTS - vat
        rows.append(dict(case=label, gross=gross, vat=vat, stripe=s_net, stripe_tax=s_net_tax,
                         paddle=p_net, managed=mp_net))
    return rows


def fixed_costs() -> list[tuple[str, float]]:
    out = []
    for i, name in enumerate(["low", "base", "high"]):
        m = ACCOUNTANT_MONTH[i] + BANK_MONTH[i] + OTHER_MONTH[i]
        out.append((name, m * 12))
    return out


def distribution(profit: float) -> dict:
    std_div = profit * (1 - CIT_STANDARD)            # PIT 0% on CIT-taxed dividends [S100]
    alt_div_gross = profit * (1 - CIT_ALT)
    alt_div = alt_div_gross * (1 - PIT_ALT)
    return dict(profit=profit, standard_to_owner=std_div, standard_tax=profit - std_div,
                alternative_to_owner=alt_div, alternative_tax=profit - alt_div,
                retained_tax=0.0)


def main() -> None:
    L = []
    w = L.append
    w("# Operator economics: Latvia-based seller (generated by `models/operator_economics.py`)\n")
    w("EUR; ECB rate 1.1206 USD/EUR (2026-10-09). Sources: Stripe [S104], Paddle [S105], Latvian tax [S100][S099], "
      "Enterprise Register [S102]. Simplified illustration: **not tax advice**. Items marked ASSUMPTION are placeholders.\n")
    w("## A. What the seller keeps from one EUR 49 (net) monthly subscription, by customer type and payment route\n")
    w("| Customer | Customer pays | VAT in price | Stripe direct, seller files VAT | + Stripe Tax Basic | Paddle (merchant of record) | Stripe Managed Payments (MoR, LV eligibility unconfirmed) |")
    w("|---|---|---|---|---|---|---|")
    for r in scenario_subscription():
        w(f"| {r['case']} | €{r['gross']:.2f} | €{r['vat']:.2f} | €{r['stripe']:.2f} | €{r['stripe_tax']:.2f} | "
          f"€{r['paddle']:.2f} | €{r['managed']:.2f} |")
    w("\nReading the table (CALCULATION):\n"
      "- Direct Stripe processing leaves the seller about 94–98% of the net price, depending on card type and currency conversion. A merchant of record (MoR) leaves about 93–94% (Paddle) or 91–95% (Stripe Managed Payments).\n"
      "- The MoR premium against direct Stripe ranges from about €0.1 (US card with currency conversion) to €2.3 (EU consumer) per €49 sale, i.e. 0–5% of revenue. "
      "In exchange, the MoR becomes the seller of record. It registers, collects and files indirect taxes abroad and handles disputes [S105][S104].\n"
      "- Whether the premium is worth paying depends on the compliance workload it replaces (OSS returns, non-EU registrations, dispute handling). That workload is not quantified here (UNKNOWN; ask an accountant for a quote).\n"
      "- US state sales tax and other non-EU indirect taxes on digital services are **not modelled**. A MoR handles them, and direct sellers must check them.\n")
    w("## B. Fixed cost of a small Latvian SIA (per year)\n")
    w("| Case | Recurring admin cost/year | One-off |\n|---|---|---|")
    for name, y in fixed_costs():
        w(f"| {name} | €{y:,.0f} (ASSUMPTION: bookkeeping, bank, tools) | €{SIA_FEE:.0f} state fee [S102]; share capital ≥ €2,800 is equity, not a cost [S102] |")
    w("\n## C. From company profit to owner (Latvian CIT on distribution)\n")
    w("| Profit distributed | Standard regime: owner receives | tax | Alternative regime (individual-owned): owner receives | tax | If retained in company |")
    w("|---|---|---|---|---|---|")
    for p in [10_000, 50_000, 100_000]:
        d = distribution(p)
        w(f"| €{p:,} | €{d['standard_to_owner']:,.0f} | €{d['standard_tax']:,.0f} | €{d['alternative_to_owner']:,.0f} | "
          f"€{d['alternative_tax']:,.0f} | €0 CIT until distributed |")
    w("\nUnder the two regimes as KPMG describes them [S100], the owner's take is almost identical (80.0% vs 79.9% of distributed profit). "
      "Ask an accountant what the alternative regime actually changes, such as interaction with the 3% surcharge above €200k or the timing. "
      "Retained profit is untaxed, which favours reinvestment (CALCULATION from published rates).\n")
    w("## D. Buying model/API services as an internal agent operator\n")
    api_usd = 2_000
    api_eur = api_usd / USD_PER_EUR
    rc = api_eur * VAT_LV
    w(f"A USD {api_usd:,}/month API bill (≈€{api_eur:,.0f}) from a non-Latvian provider is a B2B service taxed where the buyer is established "
      f"(VAT Law s.19(1)). The Latvian buyer self-assesses 21% VAT ≈ €{rc:,.0f} under reverse charge (s.88/89 [S099]). For a fully taxable, "
      "VAT-registered business this is reported and deducted in the same return, so it is cash-neutral. Under s.59(6), receiving such services "
      "removes the €50,000 small-business registration exemption, so even a very small company buying foreign APIs or cloud must be VAT-registered "
      "(per the 2024 English translation; confirm against the current text with an adviser). Under the micro-enterprise tax regime, taxpayers must not be VAT payers [S100], "
      "so the two rules appear to be in tension for agent businesses buying foreign APIs (INTERPRETATION requiring professional confirmation).\n")
    (OUT / "operator_economics_results.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
