#!/usr/bin/env python3
"""v1.2 checks: figures quoted in the decision package and paper match model outputs; tax arithmetic sanity.

Run: python3 -I verification/check_numbers_v12.py   (after models/route_economics.py and models/cost_model.py)
"""
import csv, importlib.util, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
fails, passes = [], 0


def load(name, rel):
    spec = importlib.util.spec_from_file_location(name, ROOT / rel)
    m = importlib.util.module_from_spec(spec); sys.modules[name] = m; spec.loader.exec_module(m); return m


def check(cond, msg):
    global passes
    if cond:
        passes += 1
    else:
        fails.append(msg)


def text(rel):
    return (ROOT / rel).read_text()


def has(rel, s):
    check(s in text(rel), f"{rel}: expected text not found: {s!r}")


re_ = load("route_economics", "models/route_economics.py")
base = {k: re_.steady_month(re_.R[k]["base"]) for k in ("R1", "R2", "R3", "R4")}
th = {k: re_.take_home(base[k]["op_profit"], base[k]["revenue"], re_.R[k]["base"].eu_b2b_share, base[k]["cash_costs"]) for k in base}
eur = lambda x: f"€{x:,.0f}"

# 1. figures quoted in brief, economics intro and paper (base = newcomer; high = with network)
for k in base:
    se = th[k]["self_employed"]; hrs = base[k]["hours"]
    has("package/01-decision-brief.md", f"{eur(se)}/month for ~{hrs:.0f} h")
    has("package/04-economics-intro.md", f"| {eur(base[k]['revenue'])} | {hrs:.0f} | {eur(se)} | €{se/hrs:.1f} |")
    fy_new = re_.first_year_rates(re_.R[k]["base"])[1]; fy_net = re_.first_year_rates(re_.R[k]["high"])[1]
    fy_adv = re_.first_year_rates(re_.adverse(re_.R[k]["base"]))[1]
    has("package/01-decision-brief.md", f"€{fy_new:.1f} / €{fy_net:.1f}")
    has("package/04-economics-intro.md", f"€{fy_new:.1f} / €{fy_net:.1f}")
    check(fy_adv < 0, f"{k}: adverse first year expected to be a loss")
    has("package/01-decision-brief.md", f"(−€{abs(fy_adv):.1f}/h)")
fys = [re_.first_year_rates(re_.R[k]["base"])[1] for k in base]; fyh = [re_.first_year_rates(re_.R[k]["high"])[1] for k in base]
check(round(min(fys)) == 3 and round(max(fys)) == 11, f"newcomer first-year range {fys}")
check(round(min(fyh)) == 23 and round(max(fyh)) == 36, f"network first-year range {fyh}")
check(abs(re_.BENCH_LV_PROF_NET - 8.69) < 0.005, "net benchmark 8.69")

# 2. MUN vs self-employed (hypothetical non-EU client mix)
diffs = {k: th[k]["mun"] - th[k]["self_employed"] for k in base}
check(round(diffs["R4"]) == -161 and round(diffs["R3"]) == 5, f"MUN-SE differences changed: {diffs}")
has("package/01-decision-brief.md", "€161 a month less (R4) to €5 a month more (R3)")

# 3. dossier tables are generated by package/build_package.py from the model; verify a sample cell each
d = {"R1": "package/03-dossiers/R1-agent-risk-review.md", "R2": "package/03-dossiers/R2-coding-agent-enablement.md",
     "R3": "package/03-dossiers/R3-support-agent-evaluation.md", "R4": "package/03-dossiers/R4-workflow-automations.md"}
for k, rel in d.items():
    vals = [re_.take_home(re_.steady_month(re_.R[k][c])["op_profit"], re_.steady_month(re_.R[k][c])["revenue"], re_.R[k][c].eu_b2b_share, re_.steady_month(re_.R[k][c])["cash_costs"])["self_employed"] for c in ("low", "base", "high")]
    has(rel, " | ".join(eur(v) for v in vals))

# 4. defer cash range
lo = re_.DEFER["low"][0] + 3 * re_.DEFER["low"][2]; hi = re_.DEFER["high"][0] + 3 * re_.DEFER["high"][2]
has("package/01-decision-brief.md", f"€{lo:,}–{hi:,}")

# 5. tax arithmetic sanity
t = re_.take_home(1000, 2000, 0.0, 0)
check(abs(t["se_social"] - (0.3107 * 780 + 0.10 * 220)) < 0.01, "self-employed social contribution formula (>= €780)")
check(abs(re_.take_home(500, 800, 0.0, 0)["se_social"] - 50) < 0.01, "below €780: 10% pension only [S125]")
check(abs(t["sia_dividend"] - 800) < 0.01, "SIA: net dividend = profit × 0.8 (CIT 20% of gross)")
check(abs(t["mun"] - (1000 - 0.25 * 2000)) < 0.01, "MUN = profit − 25% of turnover (no foreign costs)")
check(re_.take_home(1000, 5000, 0.0, 0)["mun"] is None, "MUN ineligible above €50k/yr turnover")

# 6. VAT special-registration cost in paper and brief
has("paper/sections/091-operating-from-latvia.md", "€31.50 a month (€378 a year)")
check(abs(150 * 0.21 - 31.5) < 1e-9, "21% of €150")

# 7. cost model v1.2 labour table quoted in paper
rows = list(csv.reader(open(ROOT / "models/cost_model_results.csv")))
v12 = {(r[2], r[3]): float(r[4]) for r in rows if r[0] == "labour_v12"}
for j, (us, loc) in {"EU27": ("35%", "38%"), "Germany": ("38%", "40%"), "Latvia": ("17%", "28%")}.items():
    check(f"{v12[(j, 'prod_saving_us_eng')]:.0%}" == us and f"{v12[(j, 'prod_saving_local_eng')]:.0%}" == loc, f"labour v12 {j}")
    has("paper/sections/05-costs.md", f"| {j} | {us} | {loc} |")

# 8. register ranks quoted in §12.4
reg = {r["id"]: r for r in csv.DictReader(open(ROOT / "opportunities/opportunity-register.csv"))}
for oid, sc in {"O07": "73", "O13": "68", "O03": "68", "O02": "63"}.items():
    check(str(reg[oid]["total"]).startswith(sc), f"register {oid} total {reg[oid]['total']} != {sc}")
has("paper/sections/08-governance-market.md", "| O07 | 73 (70) |")

# 9. every [S###] in package resolves
ids = {r["id"] for r in csv.DictReader(open(ROOT / "research/sources.csv"))}
for f in list((ROOT / "package").rglob("*.md")):
    for sid in set(re.findall(r"\[(S\d{3})\]", f.read_text())):
        check(sid in ids, f"{f.name}: unresolved {sid}")

print(f"{passes} checks passed, {len(fails)} failed")
for m in fails:
    print("FAIL:", m)
sys.exit(1 if fails else 0)
